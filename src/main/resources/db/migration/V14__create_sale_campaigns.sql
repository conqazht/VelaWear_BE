    ADD COLUMN resources_released_at TIMESTAMPTZ,
    ADD COLUMN checkout_idempotency_key VARCHAR(100),
    ADD COLUMN checkout_request_hash VARCHAR(64);

ALTER TABLE order_items
    ADD COLUMN list_price NUMERIC(15,2),
    ADD COLUMN price_source VARCHAR(30) NOT NULL DEFAULT 'BASE',
    ADD COLUMN sale_campaign_item_id BIGINT,
    ADD COLUMN sale_campaign_code VARCHAR(50),
    ADD COLUMN sale_campaign_name VARCHAR(255);

UPDATE order_items SET list_price = price WHERE list_price IS NULL;
ALTER TABLE order_items ALTER COLUMN list_price SET NOT NULL;

ALTER TABLE order_items
    ADD CONSTRAINT fk_order_items_sale_campaign_item
        FOREIGN KEY (sale_campaign_item_id) REFERENCES sale_campaign_items(id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_order_items_list_price CHECK (list_price >= 0),
    ADD CONSTRAINT ck_order_items_price_source CHECK (price_source IN ('BASE', 'STANDARD_SALE', 'FLASH_SALE')),
    ADD CONSTRAINT ck_order_items_sale_source CHECK (
        (price_source = 'BASE' AND sale_campaign_item_id IS NULL)
        OR (price_source IN ('STANDARD_SALE', 'FLASH_SALE') AND sale_campaign_item_id IS NOT NULL)
    );

CREATE TABLE sale_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    campaign_item_id BIGINT NOT NULL,
    order_item_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    reserved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    reversed_at TIMESTAMPTZ,
    CONSTRAINT pk_sale_allocations PRIMARY KEY (id),
    CONSTRAINT uq_sale_allocations_order_item UNIQUE (order_item_id),
    CONSTRAINT fk_sale_allocations_item FOREIGN KEY (campaign_item_id) REFERENCES sale_campaign_items(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sale_allocations_order_item FOREIGN KEY (order_item_id) REFERENCES order_items(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sale_allocations_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_sale_allocations_quantity CHECK (quantity > 0),
    CONSTRAINT ck_sale_allocations_status CHECK (status IN ('RESERVED', 'CONFIRMED', 'RELEASED', 'REVERSED'))
);

