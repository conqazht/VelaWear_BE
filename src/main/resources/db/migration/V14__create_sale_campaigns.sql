-- Sale Campaign expand migration. V15 removes the legacy product_variants.sale_price
-- after the application has switched to campaign-backed pricing.

CREATE TABLE sale_campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    banner_url VARCHAR(500),
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_by BIGINT,
    published_by BIGINT,
    published_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sale_campaigns PRIMARY KEY (id),
    CONSTRAINT uq_sale_campaigns_code UNIQUE (code),
    CONSTRAINT fk_sale_campaigns_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_sale_campaigns_published_by FOREIGN KEY (published_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT ck_sale_campaigns_type CHECK (type IN ('STANDARD', 'FLASH')),
    CONSTRAINT ck_sale_campaigns_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED')),
    CONSTRAINT ck_sale_campaigns_time CHECK (ends_at > starts_at)
);

CREATE TABLE sale_campaign_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    campaign_id BIGINT NOT NULL,
    variant_id BIGINT NOT NULL,
    reference_price NUMERIC(15,2) NOT NULL,
    promotional_price NUMERIC(15,2) NOT NULL,
    quota INTEGER,
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    sold_quantity INTEGER NOT NULL DEFAULT 0,
    max_per_customer INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sale_campaign_items PRIMARY KEY (id),
    CONSTRAINT uq_sale_campaign_items_campaign_variant UNIQUE (campaign_id, variant_id),
    CONSTRAINT fk_sale_campaign_items_campaign FOREIGN KEY (campaign_id) REFERENCES sale_campaigns(id) ON DELETE CASCADE,
    CONSTRAINT fk_sale_campaign_items_variant FOREIGN KEY (variant_id) REFERENCES product_variants(id) ON DELETE RESTRICT,
    CONSTRAINT ck_sale_campaign_items_prices CHECK (
        reference_price >= 0 AND promotional_price > 0 AND promotional_price < reference_price
    ),
    CONSTRAINT ck_sale_campaign_items_quota CHECK (quota IS NULL OR quota > 0),
    CONSTRAINT ck_sale_campaign_items_reserved CHECK (reserved_quantity >= 0),
    CONSTRAINT ck_sale_campaign_items_sold CHECK (sold_quantity >= 0),
    CONSTRAINT ck_sale_campaign_items_capacity CHECK (
        quota IS NULL OR reserved_quantity + sold_quantity <= quota
    ),
    CONSTRAINT ck_sale_campaign_items_customer_limit CHECK (
        max_per_customer IS NULL OR (max_per_customer > 0 AND (quota IS NULL OR max_per_customer <= quota))
    )
);

CREATE TABLE sale_customer_usages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    campaign_item_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    purchased_quantity INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sale_customer_usages PRIMARY KEY (id),
    CONSTRAINT uq_sale_customer_usages_item_user UNIQUE (campaign_item_id, user_id),
    CONSTRAINT fk_sale_customer_usages_item FOREIGN KEY (campaign_item_id) REFERENCES sale_campaign_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_sale_customer_usages_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_sale_customer_usages_reserved CHECK (reserved_quantity >= 0),
    CONSTRAINT ck_sale_customer_usages_purchased CHECK (purchased_quantity >= 0)
);

ALTER TABLE orders
