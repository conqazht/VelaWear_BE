CREATE TABLE coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(50) NOT NULL,
    type VARCHAR(20) NOT NULL,
    value NUMERIC(15,2) NOT NULL,
    min_order_amount NUMERIC(15,2) NOT NULL DEFAULT 0,
    max_discount NUMERIC(15,2),
    usage_limit INTEGER,
    used_count INTEGER NOT NULL DEFAULT 0,
    start_date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT pk_coupons PRIMARY KEY (id),
    CONSTRAINT uq_coupons_code UNIQUE (code),
    CONSTRAINT ck_coupons_type CHECK (type IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    CONSTRAINT ck_coupons_value CHECK (value >= 0),
    CONSTRAINT ck_coupons_min_order_amount CHECK (min_order_amount >= 0),
    CONSTRAINT ck_coupons_max_discount CHECK (max_discount IS NULL OR max_discount >= 0),
    CONSTRAINT ck_coupons_usage_limit CHECK (usage_limit IS NULL OR usage_limit >= 0),
    CONSTRAINT ck_coupons_used_count CHECK (used_count >= 0),
    CONSTRAINT ck_coupons_date_range CHECK (end_date > start_date),
    CONSTRAINT ck_coupons_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'EXPIRED'))
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    order_code VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    subtotal NUMERIC(15,2) NOT NULL,
    shipping_fee NUMERIC(15,2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(15,2) NOT NULL DEFAULT 0,
    final_amount NUMERIC(15,2) NOT NULL,
    receiver_name VARCHAR(150) NOT NULL,
    receiver_phone VARCHAR(20) NOT NULL,
    receiver_address VARCHAR(500) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT uq_orders_order_code UNIQUE (order_code),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'SHIPPING', 'COMPLETED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT ck_orders_subtotal CHECK (subtotal >= 0),
    CONSTRAINT ck_orders_shipping_fee CHECK (shipping_fee >= 0),
    CONSTRAINT ck_orders_discount_amount CHECK (discount_amount >= 0),
    CONSTRAINT ck_orders_final_amount CHECK (final_amount >= 0),
    CONSTRAINT ck_orders_payment_method CHECK (payment_method IN ('COD', 'VNPAY', 'MOMO', 'BANK_TRANSFER')),
    CONSTRAINT ck_orders_payment_status CHECK (payment_status IN ('UNPAID', 'PAID', 'FAILED', 'REFUNDED'))
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    variant_id BIGINT,
    product_name VARCHAR(255) NOT NULL,
    variant_name VARCHAR(255),
    sku VARCHAR(100) NOT NULL,
    image VARCHAR(500),
    price NUMERIC(15,2) NOT NULL,
    quantity INTEGER NOT NULL,
    subtotal NUMERIC(15,2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_order_items PRIMARY KEY (id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_variant FOREIGN KEY (variant_id) REFERENCES product_variants(id) ON DELETE SET NULL,
    CONSTRAINT ck_order_items_price CHECK (price >= 0),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_subtotal CHECK (subtotal >= 0),
    CONSTRAINT ck_order_items_subtotal_formula CHECK (subtotal = price * quantity),
    CONSTRAINT ck_order_items_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'RETURNED'))
);

