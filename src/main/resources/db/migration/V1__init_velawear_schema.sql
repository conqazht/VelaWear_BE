CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id BIGINT NOT NULL,
    sku VARCHAR(100) NOT NULL,
    price NUMERIC(15,2) NOT NULL,
    sale_price NUMERIC(15,2),
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    color_id BIGINT,
    size_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT pk_product_variants PRIMARY KEY (id),
    CONSTRAINT uq_product_variants_sku UNIQUE (sku),
    CONSTRAINT uq_product_variants_product_color_size UNIQUE (product_id, color_id, size_id),
    CONSTRAINT fk_product_variants_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_variants_color FOREIGN KEY (color_id) REFERENCES colors(id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_variants_size FOREIGN KEY (size_id) REFERENCES sizes(id) ON DELETE RESTRICT,
    CONSTRAINT ck_product_variants_price CHECK (price >= 0),
    CONSTRAINT ck_product_variants_sale_price CHECK (sale_price IS NULL OR sale_price >= 0),
    CONSTRAINT ck_product_variants_sale_not_greater CHECK (sale_price IS NULL OR sale_price <= price),
    CONSTRAINT ck_product_variants_stock CHECK (stock_quantity >= 0),
    CONSTRAINT ck_product_variants_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'OUT_OF_STOCK', 'DISCONTINUED'))
);

